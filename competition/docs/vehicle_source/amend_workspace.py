SRC = WS / 'src'
DOCS = ROOT / 'competition/docs/vehicle_source'


def write(rel, text):
    p = SRC / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding='utf-8', newline='\n')


def dependencies(name, additions, removals=()):
    p = SRC / name / 'package.xml'
    text = p.read_text(encoding='utf-8').replace('version="1.0.0"', 'version="1.0"')
    for kind, dep in removals:
        text = re.sub(r'\s*<' + kind + '>' + re.escape(dep) + '</' + kind + '>', '', text)
    entries = []
    for kind, dep in additions:
        entry = '<' + kind + '>' + dep + '</' + kind + '>'
        if entry not in text:
            entries.append('  ' + entry)
    text = text.replace('</package>', '\n'.join(entries) + '\n</package>')
    p.write_text(text, encoding='utf-8', newline='\n')


